// 仿 session.js 的注册模式：main.js 副作用 import 本文件即完成接线。
//
// 新增一个码 = 两步：
//   1. config/dict.js 加 CODE_XXX 常量（真实码值，0 = 关闭该守卫）
//   2. 本文件 registerCodeGuard(CODE_XXX, handler) 登记动作
// 页面层零改动：命中后请求抛 ApiError(type='guard')，不再 toast；
// 需要豁免的调用（如守卫目标页自己的接口、失败即隐藏的装饰位模块）传 options { guard: false }。
//
// 2026-10-26（v1.0.0）：按管理端 B 端契约重定 ——
//   · C 端三枚（50011 未绑手机号 / 40011 未实名 / 40012 冻结）**全部删除**：
//     管理端契约里没有这三个码，且「绑手机号」这套能力在管理端根本不存在
//     （管理端是手机号+密码**绑定管理员账号**）—— 旧守卫指向登录页的语义早已错位。
//   · 管理端只登记**两种「本人自助解决不了、必须找管理员」的账号态**，都只弹框、不跳页。
//
// ⚠️ 哪两种码**刻意不进守卫**（都是有意为之，别"顺手统一"）：
//   · 58003 绑定频控：页面级语义（同手机号 60s 内失败 5 次）→ 绑定页置灰倒计时即可恢复，
//     全局弹框反而会打断别的并发请求
//   · 40102 无权限操作：模块可能**按子类型拆权**（一个角色只有其中一类权限）——
//     一个 tab 无权不该弹阻断框、更不该把整个模块藏掉，
//     由页面自行处置（就地提示 / 置灰 / 无权限空态）
// ---------------------------------------------------------------------------

import { registerCodeGuard } from '@/services/http';
import { CODE_ACCOUNT_DISABLED, CODE_ADMIN_NO_ROLE } from '@/config/dict';
import { pushModal } from '@/store/modal';

// 账号已被禁用：登录**与绑定**接口都会回它（若本微信当前绑着的账号被禁用了，绑定也回 50008
// 而不是 58006）。两种情形的自助动作相同 —— 都只能找管理员恢复，故共用一处文案。
// 纯弹框、无跳转：用户除了联系管理员没有别的可做，不给假出口。
registerCodeGuard(CODE_ACCOUNT_DISABLED, () =>
	pushModal({
		title: '账号已被禁用',
		content: '当前账号已被禁用，请联系管理员恢复后重试',
		confirmText: '我知道了'
	})
);

// 该账号未配置角色权限（无角色 / 角色被禁用 / 角色名下无权限点）：
// 登录就被拒，故首屏是空的；弹框把原因说清楚，免得用户以为是网络问题反复重进。
registerCodeGuard(CODE_ADMIN_NO_ROLE, () =>
	pushModal({
		title: '未配置权限',
		content: '当前账号未配置角色权限，请联系管理员分配后重试',
		confirmText: '我知道了'
	})
);